	@Override
	public void SetupAnimations(T tile, float ageInTicks) {
		this.root().getAllParts().forEach(ModelPart::resetPose);
		this.animate(tile.OPEN, FabricatorModelAnimation.OPEN_BAKED, ageInTicks);
		this.animate(tile.CLOSE, FabricatorModelAnimation.CLOSE_BAKED, ageInTicks);
	}

